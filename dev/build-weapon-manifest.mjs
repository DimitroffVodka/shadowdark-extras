#!/usr/bin/env node
/**
 * Build the bundled weapon-image manifest.
 *
 * The weapon picker used to discover this art with `FilePicker.browse`, which
 * requires the `FILES_BROWSE` permission. That permission is not granted to the
 * PLAYER role by default, so for a player every browse was rejected, the scan
 * returned nothing, and the picker reported "No weapon images found in
 * assets/Weapons folder" — a claim about the folder for what was actually a
 * permission failure.
 *
 * A static JSON file needs no permission: it is served like any other module
 * asset. This script writes that file. `dev/tests/weapon-image-manifest.test.mjs`
 * asserts it still matches what is on disk, so it cannot drift silently.
 *
 * Usage: npm run weapon-manifest        (rewrite the manifest)
 *        npm run weapon-manifest -- --check   (exit 1 if stale, write nothing)
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const MODULE_ID = "shadowdark-extras";
const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const ASSET_DIR = path.join(REPO_ROOT, "assets", "Weapons");
const MANIFEST_FILE = path.join(ASSET_DIR, "manifest.json");

/** The extensions the runtime scanner accepts. Keep in step with WeaponAnimationSD. */
const IMAGE_EXTENSIONS = [".webp", ".png", ".jpg"];

/** Runtime base path, as the browse-based scanner produced it. */
const RUNTIME_BASE = `modules/${MODULE_ID}/assets/Weapons`;

/** Every image under `dir`, relative to ASSET_DIR, in stable sorted order. */
function collectImages(dir) {
	const out = [];
	for (const entry of fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
		const full = path.join(dir, entry.name);
		if (entry.isDirectory()) {
			out.push(...collectImages(full));
			continue;
		}
		if (!IMAGE_EXTENSIONS.includes(path.extname(entry.name).toLowerCase())) continue;
		out.push(path.relative(ASSET_DIR, full).split(path.sep).join("/"));
	}
	return out;
}

/**
 * The category the browse-based scanner would have derived: the image's
 * directory relative to the Weapons root, or the literal "Weapons" for a file
 * sitting directly in it. Preserved exactly so grouping in the picker is
 * unchanged by the switch away from browsing.
 */
function categoryOf(relativePath) {
	const dir = path.posix.dirname(relativePath);
	return dir === "." ? "Weapons" : dir;
}

/** The display name: basename without its extension. */
function nameOf(relativePath) {
	return path.posix.basename(relativePath).replace(/\.(webp|png|jpg)$/i, "");
}

function buildManifest() {
	if (!fs.existsSync(ASSET_DIR)) {
		throw new Error(`weapon asset directory is missing: ${ASSET_DIR}`);
	}

	const images = collectImages(ASSET_DIR).map(relative => ({
		path: `${RUNTIME_BASE}/${relative}`,
		name: nameOf(relative),
		category: categoryOf(relative),
	}));

	// De-duplicate by name, first wins — the same rule the scanner applied, so a
	// repeated basename across categories resolves identically either way.
	const seen = new Set();
	const deduped = images.filter(img => {
		if (seen.has(img.name)) return false;
		seen.add(img.name);
		return true;
	});

	return {
		_comment: "Generated by dev/build-weapon-manifest.mjs — do not edit by hand. Run `npm run weapon-manifest` after adding or removing weapon art.",
		base: RUNTIME_BASE,
		count: deduped.length,
		images: deduped,
	};
}

function serialize(manifest) {
	return `${JSON.stringify(manifest, null, "\t")}\n`;
}

const manifest = buildManifest();
const serialized = serialize(manifest);
const checkOnly = process.argv.includes("--check");

if (checkOnly) {
	const current = fs.existsSync(MANIFEST_FILE) ? fs.readFileSync(MANIFEST_FILE, "utf8") : null;
	if (current === serialized) {
		console.log(`weapon-manifest: up to date (${manifest.count} images)`);
		process.exit(0);
	}
	console.error("weapon-manifest: STALE — run `npm run weapon-manifest`");
	console.error(`  on disk: ${current === null ? "missing" : `${JSON.parse(current).count ?? "?"} images`}`);
	console.error(`  expected: ${manifest.count} images`);
	process.exit(1);
}

fs.writeFileSync(MANIFEST_FILE, serialized);
console.log(`weapon-manifest: wrote ${manifest.count} images to ${path.relative(REPO_ROOT, MANIFEST_FILE)}`);
