#!/usr/bin/env node
/**
 * Regenerate scripts/npc/creature-type-map.mjs from Shadowdark Tools (or a local JSON).
 *
 * The bundled creature-type map is a SNAPSHOT of shadowdarktools.com/reference.
 * Run this when that source updates. Node-side fetch has no CORS limit (unlike
 * the in-Foundry path), so the live fetch works here.
 *
 * Usage:
 *   node dev/regen-creature-type-map.mjs                 # fetch live, write data file
 *   node dev/regen-creature-type-map.mjs --dry           # fetch live, print summary + diff vs existing, no write
 *   node dev/regen-creature-type-map.mjs --from <bestiary-reference.json> [--dry]
 *
 * Parser (extractObjectLiteral / extractMonsterDatasets) salvaged from the
 * original Codex macro update-creature-types-from-shadowdark-tools.mjs.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const REFERENCE_URL = "https://www.shadowdarktools.com/reference";
const __dirname = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(__dirname, "..", "scripts", "npc", "creature-type-map.mjs");

const args = process.argv.slice(2);
const DRY = args.includes("--dry");
const fromIdx = args.indexOf("--from");
const FROM = fromIdx >= 0 ? args[fromIdx + 1] : null;

// Must match normalizeMonsterName in scripts/npc/CreatureTypesApp.mjs.
// dev/tests/creature-type-map-sync.test.mjs fails if these two diverge.
const norm = (s) => String(s ?? "").toUpperCase().replace(/[’']/g, "'").replace(/\s+/g, " ").trim();
const titlePrimary = (tags) => {
	const primary = String(tags ?? "").split(",")[0].trim().toLowerCase();
	return primary ? primary.charAt(0).toUpperCase() + primary.slice(1).toLowerCase() : "";
};

function extractObjectLiteral(src, start) {
	let depth = 0, inTemplate = false, escaped = false;
	for (let i = start; i < src.length; i++) {
		const c = src[i];
		if (inTemplate) {
			if (escaped) escaped = false;
			else if (c === "\\") escaped = true;
			else if (c === "`") inTemplate = false;
			continue;
		}
		if (c === "`") { inTemplate = true; continue; }
		if (c === "{" || c === "[" || c === "(") depth++;
		else if (c === "}" || c === "]" || c === ")") { depth--; if (depth === 0) return src.slice(start, i + 1); }
	}
	throw new Error("Could not parse bundled monster data.");
}

function extractMonsterDatasets(bundle) {
	const markers = ["{name:`Monster Data`", "{name:`Cursed Scrolls Monster Data`"];
	const datasets = [];
	for (const marker of markers) {
		let index = -1;
		while ((index = bundle.indexOf(marker, index + 1)) !== -1) {
			const literal = extractObjectLiteral(bundle, index);
			datasets.push(Function(`"use strict"; return (${literal});`)());
		}
	}
	if (!datasets.length) throw new Error("No monster datasets found in Shadowdark Tools bundle.");
	return datasets;
}

async function datasetsFromFetch() {
	if (typeof fetch !== "function") {
		throw new Error("global fetch unavailable (need Node >= 18) — pass --from <bestiary-reference.json>");
	}
	const html = await (await fetch(REFERENCE_URL)).text();
	const m = html.match(/<script[^>]+type=["']module["'][^>]+src=["']([^"']+)["']/i);
	if (!m) throw new Error("Could not find Shadowdark Tools app script.");
	const url = new URL(m[1], REFERENCE_URL).href;
	const bundle = await (await fetch(url)).text();
	return extractMonsterDatasets(bundle);
}

function datasetsFromJson(p) {
	const data = JSON.parse(fs.readFileSync(p, "utf8"));
	const entries = Array.isArray(data?.npcs) ? data.npcs : Array.isArray(data?.entries) ? data.entries : [];
	if (!entries.length) throw new Error(`No npcs/entries array in ${p}`);
	return [{ entries: entries.map((e) => ({ name: e.name ?? e.displayName, tags: e.type ?? e.tags ?? e.creatureType ?? "" })) }];
}

function buildMap(datasets) {
	const map = {};
	for (const ds of datasets) {
		for (const e of ds.entries ?? []) {
			const k = norm(e.name);
			if (!k || (k in map)) continue; // first occurrence wins
			map[k] = titlePrimary(e.tags);
		}
	}
	const sorted = {};
	for (const k of Object.keys(map).sort()) sorted[k] = map[k];
	return sorted;
}

function render(map) {
	const values = [...new Set(Object.values(map))].filter(Boolean).sort();
	const meta = {
		source: REFERENCE_URL,
		generatedAt: new Date().toISOString().slice(0, 10),
		entryCount: Object.keys(map).length,
		taxonomy: values
	};
	return `/**
 * Creature Type Map — Shadowdark Extras
 *
 * AUTO-GENERATED by dev/regen-creature-type-map.mjs. Do not hand-edit.
 * Snapshot of ${REFERENCE_URL}. Keys are NORMALIZED names (uppercase,
 * single-spaced, straight apostrophes). Values are the primary tag
 * (before the first comma), Title-cased — the SD-native taxonomy.
 *
 * Runtime mapping only; the compendium is never mutated. Effective type =
 * manual flag override > this map > "" (none).
 */

export const CREATURE_TYPE_MAP_META = ${JSON.stringify(meta, null, 2)};

export const CREATURE_TYPE_MAP = ${JSON.stringify(map)};
`;
}

(async () => {
	const datasets = FROM ? datasetsFromJson(FROM) : await datasetsFromFetch();
	const map = buildMap(datasets);
	const values = [...new Set(Object.values(map))].filter(Boolean).sort();
	console.log(`source: ${FROM ? `file ${FROM}` : "live fetch"}`);
	console.log(`entries: ${Object.keys(map).length} | types (${values.length}): ${values.join(", ")}`);

	if (DRY) {
		let verdict;
		try {
			const cur = fs.readFileSync(OUT, "utf8");
			const head = "CREATURE_TYPE_MAP = ";
			const slice = cur.slice(cur.indexOf(head) + head.length);
			const curMap = JSON.parse(slice.slice(0, slice.indexOf("};") + 1));
			const curKeys = Object.keys(curMap);
			const newKeys = Object.keys(map);
			const onlyNew = newKeys.filter((k) => !(k in curMap));
			const onlyOld = curKeys.filter((k) => !(k in map));
			const changed = newKeys.filter((k) => k in curMap && curMap[k] !== map[k]);
			verdict = JSON.stringify(curMap) === JSON.stringify(map);
			console.log("matches existing scripts/npc/creature-type-map.mjs:", verdict);
			if (!verdict) console.log({ added: onlyNew.slice(0, 20), removed: onlyOld.slice(0, 20), retagged: changed.slice(0, 20).map((k) => `${k}: ${curMap[k]}->${map[k]}`) });
		} catch (e) {
			console.log("compare failed:", e.message);
		}
		console.log("[--dry] no file written");
		return;
	}

	fs.writeFileSync(OUT, render(map));
	console.log("wrote", path.relative(path.join(__dirname, ".."), OUT));
})().catch((e) => { console.error("regen failed:", e.message); process.exit(1); });
